"""Generate docs/RESULTS.md from data/results/results.json and data/subnet_report.json (numbers never typed by hand)."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
R = json.loads((ROOT / "data" / "results" / "results.json").read_text())
S = json.loads((ROOT / "data" / "subnet_report.json").read_text())
SEXES = ("male", "female")
COLS = [("baseline", "Baseline (w≥5)"), ("thr10", "Weight ≥ 10"), ("signflip", "Low-conf signs flipped"),
        ("shuffled", "Shuffled connectome"), ("scrambled_audio", "Scrambled audio")]
CHECK_NAMES = {"baseline_significant": "significant at baseline", "survives_threshold_10": "survives w≥10",
               "survives_sign_flip": "survives sign flip", "absent_or_smaller_in_shuffled": "smaller on shuffled wiring",
               "absent_or_smaller_with_scrambled_audio": "smaller with scrambled audio"}


def ci(e: dict) -> str:
    return f"{e['mean']:.2f} [{e['ci'][0]:.2f}, {e['ci'][1]:.2f}]"


def grid_table(sex: str, key: str) -> str:
    g = R["meta"]["grid"]
    rows = R["per_sex"][sex][key]
    head = "| IPI (ms) \\ carrier (Hz) | " + " | ".join(str(f) for f in g["carrier_hz"]) + " |"
    sep = "|---" * (len(g["carrier_hz"]) + 1) + "|"
    body = [f"| **{ipi}** | " + " | ".join(f"{v:.2f}" for v in row) + " |" for ipi, row in zip(g["ipi_ms"], rows)]
    return "\n".join([head, sep, *body])


def main() -> None:
    m = R["meta"]
    out = [
        "# Results",
        "",
        f"_Generated by `docs/make_results.py` from `data/results/results.json` — sweep mode **{m['mode']}**, "
        f"{len(m['grid']['ipi_ms'])}×{len(m['grid']['carrier_hz'])} grid, {len(m['seeds'])} seeds, "
        f"{m['grid']['duration_s']} s per trial, config `{m['config_hash']}`, created {m['created']}, runtime {m['runtime_s'] / 3600:.1f} h._",
        "",
        "All values are firing rates (Hz) of the **target set** (song detectors + receptivity cells) — **model predictions**, "
        "with bootstrap 95% confidence intervals over seeds.",
        "",
        "## 1. Subnetworks",
        "",
        "| | Male (MaleCNS v1.0) | Female (FlyWire v783) |",
        "|---|---|---|",
        f"| Neurons / edges | {S['male']['n_neurons']:,} / {S['male']['n_edges']:,} | {S['female']['n_neurons']:,} / {S['female']['n_edges']:,} |",
        "| JO seeds by subtype | " + " · ".join(f"{k} {v}" for k, v in S["male"]["jo_subtypes"].items()) + " | "
        + " · ".join(f"{k} {v}" for k, v in S["female"]["jo_subtypes"].items()) + " |",
    ]
    for k in S["male"]["targets"]:
        cell = lambda s: f"{S[s]['targets'][k]['in_dataset']} found ({S[s]['targets'][k]['within_hops']} within 3 hops): " + ", ".join(S[s]["targets"][k]["types"][:10])  # noqa: E731
        out.append(f"| {k.replace('_', ' ').capitalize()} | {cell('male')} | {cell('female')} |")
    out += ["", "## 2. Validation check", "",
            "Does the target set fire more for pulse song (35 ms IPI, 220 Hz) than for phase-scrambled audio **and** white noise?", "",
            "| | Pulse song | Scrambled | Noise | Sine | Pulse − scrambled | Pulse − noise | Result |", "|---|---|---|---|---|---|---|---|"]
    for sex in SEXES:
        rf, v = R["per_sex"][sex]["refs"], R["validation"][sex]
        out.append(f"| **{sex}** | " + " | ".join(f"{rf[k]['mean']:.2f}" for k in ("pulse35", "scrambled35", "noise", "sine"))
                   + f" | {ci(v['pulse_gt_scrambled'])} | {ci(v['pulse_gt_noise'])} | **{v['result']}** |")
    out += ["", "## 3. IPI × carrier sweep", ""]
    for sex in SEXES:
        pk = R["per_sex"][sex]["peak"]
        out += [f"### {sex.capitalize()} — pulse song", "",
                f"Peak: **{pk['ipi_ms']} ms IPI / {pk['carrier_hz']} Hz ({pk['rate_hz']:.2f} Hz)**" if pk else "Peak: **none — no target response anywhere on the grid**", "",
                grid_table(sex, "grid_mean"), "", f"<details><summary>{sex.capitalize()} — phase-scrambled control grid</summary>", "",
                grid_table(sex, "grid_scrambled_mean"), "", "</details>", ""]
    out += ["![Sweep heatmaps](images/13-pipeline-heatmaps.png)", "", "## 4. Robustness of effects", "",
            "An effect is **robust** only if it is significant at baseline, keeps its sign and significance with weight ≥ 10 and with "
            "low-confidence transmitter signs flipped, **and** is absent or significantly smaller on the degree-preserving shuffled connectome "
            "(for IPI tuning, also smaller with phase-scrambled audio).", "",
            "| Effect | " + " | ".join(n for _, n in COLS) + " | Failed checks | Verdict |", "|---" * (len(COLS) + 3) + "|"]
    for name, r in R["robust"].items():
        cells = [ci(r["effects"][c]) if c in r["effects"] else "—" for c, _ in COLS]
        failed = [CHECK_NAMES.get(k, k) for k, ok in r["checks"].items() if not ok]
        out.append(f"| {name.replace(':', ' · ').replace('_', ' ')} | " + " | ".join(cells)
                   + f" | {', '.join(failed) or 'none'} | **{'ROBUST' if r['robust'] else 'not robust'}** |")
    stages = ["JO", "AMMC", "Wedge", "Song det.", "Receptivity"]
    out += ["", "## 5. Where the signal goes (pulse song, mean rate per neuron by stage)", "",
            "| | " + " | ".join(stages) + " |", "|---" * (len(stages) + 1) + "|"]
    for sex in SEXES:
        out.append(f"| {sex} | " + " | ".join(f"{v:.2f}" for v in R["per_sex"][sex]["stage_rates_pulse35"]) + " |")
    (ROOT / "docs" / "RESULTS.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("docs/RESULTS.md written")


if __name__ == "__main__":
    main()
